# Транслітерація латиниця → кирилиця (базова, для CRM-фідів)
# ---------------------------------------------------------------------------
_TRANSLIT_MAP: dict[str, str] = {
    # голосні
    "ya": "я", "yu": "ю", "ye": "є", "yi": "ї",
    "yo": "йо", "ia": "я", "iu": "ю", "ie": "є",
    "kh": "х", "zh": "ж", "ch": "ч", "sh": "ш",
    "shch": "щ", "ts": "ц",
    # однобуквені (після двобуквених)
    "a": "а", "b": "б", "v": "в", "h": "г", "g": "г",
    "d": "д", "e": "е", "z": "з", "i": "і", "y": "і",
    "j": "й", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "r": "р", "s": "с", "t": "т",
    "u": "у", "f": "ф", "c": "к", "q": "к", "w": "в",
    "x": "кс",
}

_TRANSLIT_RE = re.compile(
    r"shch|ya|yu|ye|yi|yo|ia|iu|ie|kh|zh|ch|sh|ts|[a-z]"
)


def _translit_to_cyrillic(s: str) -> str:
    """Базова транслітерація lat→cyr. Використовується лише якщо слово не містить кирилиці."""
    return _TRANSLIT_RE.sub(lambda m: _TRANSLIT_MAP.get(m.group(), m.group()), s)


def _has_cyrillic(s: str) -> bool:
    return bool(re.search(r"[а-яіїєёА-ЯІЇЄЁʼ']", s))


_APOSTROPHE_CHARS = "ʼ'`´'ʻ'‚'‛'＇''\u2018\u2019\u201a\u201b"

# Латинські «двійники» в CRM-фідах (Aнастасія, Oксана тощо)
_LATIN_TO_CYRILLIC_IN_MIXED: dict[str, str] = {
    "a": "а",
    "b": "в",
    "c": "с",
    "e": "е",
    "h": "н",
    "i": "і",
    "k": "к",
    "m": "м",
    "o": "о",
    "p": "р",
    "t": "т",
    "x": "х",
    "y": "у",
}


def _fix_latin_cyrillic_homoglyphs(s: str) -> str:
    """Якщо в рядку є кирилиця — підмінити схожі латинські літери."""
    if not re.search(r"[а-яіїєґ]", s):
        return s
    return "".join(_LATIN_TO_CYRILLIC_IN_MIXED.get(ch, ch) for ch in s)


def _normalize_name_string(name: str) -> str:
    s = unicodedata.normalize("NFC", str(name))
    s = s.strip().casefold()
    for ch in _APOSTROPHE_CHARS:
        s = s.replace(ch, "'")
    s = _fix_latin_cyrillic_homoglyphs(s)
    # CRM: «Наталiя» з латинською i
    s = re.sub(r"(?<=[а-яёіїєьъ])i(?=[а-яёіїєьъ])", "і", s)
    s = re.sub(r"(?<=[а-яёіїєьъ])i", "і", s)
    s = re.sub(r"i(?=[а-яёіїєьъ])", "і", s)
    return s


def _normalize_single_token(piece: str) -> str:
    """Один токен (слово) після нормалізації."""
    token = _normalize_name_string(piece)
    token = token.strip(".,;:-—–()[]\"«»")
    return token


def iter_name_tokens(name: str | None) -> list[str]:
    """Усі слова з поля імені (ПІБ, «Прізвище Ім'я», подвійне ім'я)."""
    if not name:
        return []
    normalized = _normalize_name_string(name)
    if not normalized:
        return []
    return [t for t in re.split(r"[\s,]+", normalized) if t]


def normalize_firstname_token_for_match(name: str | None) -> str:
    """Перший токен (legacy); для статі краще detect_gender_from_firstname."""
    tokens = iter_name_tokens(name)
    return tokens[0] if tokens else ""


def _normalize_name_token(name: str | None) -> str:
    return normalize_firstname_token_for_match(name)


def _token_lookup_variants(token: str) -> tuple[str, ...]:
    no_apos = token.replace("'", "")
    if no_apos == token:
        return (token,)
    return (token, no_apos)


def _gender_for_single_token(token: str) -> str:
    """male | female | unknown для одного слова."""
    if not token:
        return "unknown"

    unisex_lower = {n.casefold() for n in UNISEX_FIRST_NAMES_RAW}
    for variant in _token_lookup_variants(token):
        if variant in unisex_lower:
            return "unknown"
        if variant in MALE_FIRST_NAMES:
            return "male"
        if variant in FEMALE_FIRST_NAMES:
            return "female"
        if not _has_cyrillic(variant):
            cyr = _translit_to_cyrillic(variant)
            for c in _token_lookup_variants(cyr):
                if c in MALE_FIRST_NAMES:
                    return "male"
                if c in FEMALE_FIRST_NAMES:
                    return "female"
    return "unknown"


def _combine_name_fields(firstname: str | None, lastname: str | None) -> str:
    parts = [str(x).strip() for x in (firstname, lastname) if x and str(x).strip()]
    return " ".join(parts)


def gender_is_match_for_sql(
    firstname: str | None,
    lastname: str | None,
    mode: str,
) -> int:
    """SQLite UDF: 1 якщо стать за firstname + lastname збігається з mode."""
    expected = (mode or "").strip().lower()
    if expected not in ("male", "female", "unknown"):
        return 0
    actual = detect_gender_from_firstname(_combine_name_fields(firstname, lastname))
    return 1 if actual == expected else 0


def _build_name_sets() -> tuple[frozenset[str], frozenset[str]]:
    male = {n.strip().lower() for n in MALE_FIRST_NAMES_RAW if n and n.strip()}
    female = {n.strip().lower() for n in FEMALE_FIRST_NAMES_RAW if n and n.strip()}
    unisex = {n.strip().lower() for n in UNISEX_FIRST_NAMES_RAW if n}
    # видаляємо юнісекс з обох
    male -= unisex
    female -= unisex
    # видаляємо перетин (конфлікт)
    overlap = male & female
    male -= overlap
    female -= overlap
    return frozenset(male), frozenset(female)


MALE_FIRST_NAMES, FEMALE_FIRST_NAMES = _build_name_sets()


def detect_gender_from_firstname(name: str | None) -> str:
    """Повертає 'male' | 'female' | 'unknown'.

    Перевіряє слова зліва направо; перше розпізнане ім'я визначає стать.
    Так прізвища на кшталт «Демʼян» не суперечать «Вікторія»; «Петренко Анастасія» теж працює.
    """
    tokens = iter_name_tokens(name)
    if not tokens:
        return "unknown"

    for token in tokens:
        g = _gender_for_single_token(token)
        if g in ("male", "female"):
            return g
    return "unknown"


